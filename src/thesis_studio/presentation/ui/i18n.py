def get_lang() -> str:
    """Get current language preference."""
    try:
        lang = app.storage.user.get("lang")
    except RuntimeError:
        return DEFAULT_LANG
    if lang is None or lang not in SUPPORTED_LANGS:
        return DEFAULT_LANG
    return lang


def set_lang(lang: str) -> None:
    """Set language preference."""
    app.storage.user["lang"] = lang


def toggle_lang() -> str:
    """Toggle language, return new language."""
    new = "zh" if get_lang() == "en" else "en"
    set_lang(new)
    return new


def t(key: str, **kwargs: object) -> str:
    """Translate text. Supports {placeholder} formatting."""
    lang = get_lang()
    table = _TRANSLATIONS.get(lang, _TRANSLATIONS[DEFAULT_LANG])
    text = table.get(key, key)
    if kwargs:
        text = text.format(**kwargs)
    return text


